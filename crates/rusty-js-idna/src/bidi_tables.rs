#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bidi_ranges_are_sorted_non_overlapping() {
        assert_eq!(UNICODE_VERSION, "17.0.0");
        let mut previous_hi = None;
        for (index, &(lo, hi, _)) in BIDI_CLASS_RANGES.iter().enumerate() {
            assert!(lo <= hi, "bidi range {index} is inverted");
            assert!(
                hi <= 0x10FFFF,
                "bidi range {index} exceeds Unicode scalar range"
            );
            if let Some(prev) = previous_hi {
                assert!(prev < lo, "bidi range {index} overlaps or is unsorted");
            }
            previous_hi = Some(hi);
        }
    }

    #[test]
    fn representative_bidi_classes_match_unicode_data() {
        assert_eq!(bidi_class('a' as u32), BidiClass::L);
        assert_eq!(bidi_class('0' as u32), BidiClass::EN);
        assert_eq!(bidi_class(0x05D0), BidiClass::R);
        assert_eq!(bidi_class(0x0627), BidiClass::AL);
        assert_eq!(bidi_class(0x0661), BidiClass::AN);
        assert_eq!(bidi_class(0x0308), BidiClass::NSM);
        assert_eq!(bidi_class(0x202E), BidiClass::Other);
    }
}
