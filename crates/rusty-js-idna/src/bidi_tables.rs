pub fn bidi_class(cp: u32) -> BidiClass {
    match BIDI_CLASS_RANGES.binary_search_by(|&(lo, hi, _)| {
        if cp < lo {
            core::cmp::Ordering::Greater
        } else if cp > hi {
            core::cmp::Ordering::Less
        } else {
            core::cmp::Ordering::Equal
        }
    }) {
        Ok(index) => BIDI_CLASS_RANGES[index].2,
        Err(_) => BidiClass::L,
    }
}

