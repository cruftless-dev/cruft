pub(crate) fn long_display_name(
    primary_identifier: &str,
    epoch_ms: i64,
    daylight: bool,
) -> Option<&'static str> {
    let hyphen_normalized = primary_identifier.replace('_', "-").replace(' ', "-");
    let underscore_normalized = primary_identifier.replace('-', "_").replace(' ', "_");
    let space_normalized = primary_identifier.replace(['-', '_'], " ");
    let duals =
        crate::intl_locale_data::intl_time_zone_values_generated::link_duals(primary_identifier);
    let mut candidates = vec![
        primary_identifier,
        hyphen_normalized.as_str(),
        underscore_normalized.as_str(),
        space_normalized.as_str(),
    ];
    candidates.extend(duals);
    let mapping = TIME_ZONE_METAZONES.iter().find(|row| {
        candidates
            .iter()
            .any(|candidate| row.zone.eq_ignore_ascii_case(candidate))
            && epoch_ms >= row.from_ms
            && epoch_ms < row.to_ms
    })?;
    if daylight && mapping.metazone == "GMT" {
        if candidates
            .iter()
            .any(|candidate| candidate.eq_ignore_ascii_case("Europe/London"))
        {
            return Some("British Summer Time");
        }
        if candidates
            .iter()
            .any(|candidate| candidate.eq_ignore_ascii_case("Europe/Dublin"))
        {
            return Some("Irish Standard Time");
        }
        return None;
    }
    let names = METAZONE_LONG_NAMES
        .iter()
        .find(|(metazone, _, _, _)| *metazone == mapping.metazone)
        .copied()?;
    if daylight && !names.3.is_empty() {
        return Some(names.3);
    }
    if !names.2.is_empty() {
        return Some(names.2);
    }
    if !names.1.is_empty() {
        return Some(names.1);
    }
    None
}
