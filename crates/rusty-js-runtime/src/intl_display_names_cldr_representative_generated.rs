fn representative_source_locale(locale: &str) -> Option<&'static str> {
    REPRESENTATIVE_SOURCE_LOCALES
        .iter()
        .find_map(|&(tag, source)| if tag == locale { Some(source) } else { None })
}

fn locale_candidates(locale: &str) -> [Option<&str>; 3] {
    let mut split = locale.splitn(3, '-');
    let primary = split.next().unwrap_or(locale);
    let second = split.next();
    let script = second.and_then(|part| {
        if part.len() == 4 {
            locale.find('-').and_then(|first_dash| {
                locale[first_dash + 1..]
                    .find('-')
                    .map(|second_dash| &locale[..first_dash + 1 + second_dash])
            })
        } else {
            None
        }
    });
    let primary_candidate = if script.is_some() {
        None
    } else {
        Some(primary)
    };
    [Some(locale), script, primary_candidate]
}

pub(crate) fn display_name(
    locale: &str,
    display_type: &str,
    code: &str,
    language_display: &str,
) -> Option<&'static str> {
    let locale_lower = locale.to_ascii_lowercase();
    if let Some(source_locale) = representative_source_locale(&locale_lower) {
        for &(row_locale, row_type, row_code, row_language_display, row_name) in DISPLAY_NAMES {
            if row_locale == source_locale
                && row_type == display_type
                && row_code.eq_ignore_ascii_case(code)
                && row_language_display == language_display
            {
                return Some(row_name);
            }
        }
    }
    for candidate in locale_candidates(&locale_lower).into_iter().flatten() {
        for &(row_locale, row_type, row_code, row_language_display, row_name) in DISPLAY_NAMES {
            if row_locale == candidate
                && row_type == display_type
                && row_code.eq_ignore_ascii_case(code)
                && row_language_display == language_display
            {
                return Some(row_name);
            }
        }
    }
    None
}
