fn cldr_type(typ: &str, style: &str) -> &'static str {
    match (typ, style) {
        ("conjunction", "short") => "standard-short",
        ("conjunction", "narrow") => "standard-narrow",
        ("conjunction", _) => "standard",
        ("disjunction", "short") => "or-short",
        ("disjunction", "narrow") => "or-narrow",
        ("disjunction", _) => "or",
        ("unit", "short") => "unit-short",
        ("unit", "narrow") => "unit-narrow",
        ("unit", _) => "unit",
        _ => "standard",
    }
}

fn locale_candidates(locale: &str) -> [Option<&str>; 3] {
    let normalized = locale.split('.').next().unwrap_or(locale);
    let primary_end = normalized.find('-').unwrap_or(normalized.len());
    let rest = normalized.get(primary_end + 1..).unwrap_or("");
    let second_len = rest.find('-').unwrap_or(rest.len());
    let script_candidate = if second_len == 4 && primary_end + 1 + second_len < normalized.len() {
        Some(&normalized[..primary_end + 1 + second_len])
    } else {
        None
    };
    [
        Some(normalized),
        script_candidate,
        Some(&normalized[..primary_end]),
    ]
}

pub(crate) fn list_patterns(
    locale: &str,
    typ: &str,
    style: &str,
) -> Option<(&'static str, &'static str, &'static str, &'static str)> {
    let normalized = locale.replace('_', "-").to_ascii_lowercase();
    let wanted_type = cldr_type(typ, style);
    if let Some(source) = representative_source_locale(&normalized) {
        if let Ok(idx) = LIST_PATTERN_ROWS.binary_search_by(|(row_locale, row_type, ..)| {
            row_locale
                .cmp(&source)
                .then_with(|| row_type.cmp(&wanted_type))
        }) {
            let (_, _, pair, start, middle, end) = LIST_PATTERN_ROWS[idx];
            return Some((pair, start, middle, end));
        }
    }
    for candidate in locale_candidates(&normalized).into_iter().flatten() {
        if let Ok(idx) = LIST_PATTERN_ROWS.binary_search_by(|(row_locale, row_type, ..)| {
            row_locale
                .cmp(&candidate)
                .then_with(|| row_type.cmp(&wanted_type))
        }) {
            let (_, _, pair, start, middle, end) = LIST_PATTERN_ROWS[idx];
            return Some((pair, start, middle, end));
        }
    }
    None
}
