#[derive(Clone, Copy)]
struct Operands {
    n: f64,
    i: i64,
    v: i64,
    f: i64,
    t: i64,
    e: i32,
}

fn operands(n: f64, e: i32) -> Operands {
    let abs = n.abs();
    let i = abs.trunc() as i64;
    let mut frac = format!("{:.15}", abs);
    if let Some(dot) = frac.find('.') {
        let mut digits = frac.split_off(dot + 1);
        while digits.ends_with('0') {
            digits.pop();
        }
        let v = digits.len() as i64;
        let f = if digits.is_empty() {
            0
        } else {
            digits.parse().unwrap_or(0)
        };
        let t = f;
        Operands {
            n: abs,
            i,
            v,
            f,
            t,
            e,
        }
    } else {
        Operands {
            n: abs,
            i,
            v: 0,
            f: 0,
            t: 0,
            e,
        }
    }
}

fn in_range(value: i64, start: i64, end: i64) -> bool {
    value >= start && value <= end
}

fn n_is(op: Operands, values: &[i64]) -> bool {
    op.v == 0 && values.iter().any(|value| op.i == *value)
}

fn n_in(op: Operands, start: i64, end: i64) -> bool {
    op.v == 0 && in_range(op.i, start, end)
}

